  function getLang() {
    const saved = localStorage.getItem('ui_lang');
    return saved === 'ru' ? 'ru' : 'tk';
  }

  function setLang(lang) {
    const next = lang === 'ru' ? 'ru' : 'tk';
    localStorage.setItem('ui_lang', next);
    applyI18n();
    return next;
  }

  function t(key) {
    const lang = getLang();
    return (DICT[lang] && DICT[lang][key]) || (DICT.tk && DICT.tk[key]) || key;
  }

  function statusLabel(value) {
    const key = STATUS_LABEL[value];
    return key ? t(key) : value;
  }

  function anketaStatusLabel(value) {
    const key = ANKETA_STATUS[value];
    return key ? t(key) : value;
  }

  function vacancyStatusLabel(value) {
    const key = VACANCY_STATUS[value];
    return key ? t(key) : value;
  }

  function reasonLabel(text) {
    if (!text) return '';
    const key = REASON_MAP[String(text).trim()];
    return key ? t(key) : text;
  }

  function reasonsText(reasons) {
    if (!Array.isArray(reasons) || !reasons.length) return '—';
    return reasons.map(reasonLabel).join(', ');
  }

  function applyI18n() {
    const lang = getLang();
    document.documentElement.lang = lang === 'ru' ? 'ru' : 'tk';
    document.body?.setAttribute('data-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      const val = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.type !== 'button' && el.type !== 'submit') return;
      }
      el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });

    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    });

    document.querySelectorAll('.lang-switch [data-lang]').forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    document.dispatchEvent(new CustomEvent('ui-lang-changed', { detail: { lang } }));
  }

